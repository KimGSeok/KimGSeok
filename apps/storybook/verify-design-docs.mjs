import { chromium } from "playwright";
import axe from "axe-core";

const baseUrl = process.argv[2] ?? "http://127.0.0.1:3100";
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errors = [];
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
page.on("pageerror", (error) => errors.push(error.message));
await page.goto(baseUrl, { waitUntil: "networkidle" });
if (!(await page.getByRole("heading", { name: /제품을 빠르게 만들고/ }).isVisible())) throw new Error("Design Docs hero did not render.");
if ((await page.locator("body").innerText()).trim().length < 500) throw new Error("Design Docs rendered insufficient content.");
await page.getByRole("button", { name: /기준 날짜/ }).click();
const dialog = page.getByRole("dialog", { name: "기준 날짜" });
await dialog.waitFor();
const focusedBefore = await page.evaluate(() => document.activeElement?.getAttribute("aria-label"));
await page.keyboard.press("ArrowRight");
await page.waitForTimeout(40);
const focusedAfter = await page.evaluate(() => document.activeElement?.getAttribute("aria-label"));
if (!focusedBefore || !focusedAfter || focusedBefore === focusedAfter) throw new Error(`Calendar arrow navigation did not move focus (${focusedBefore} -> ${focusedAfter}).`);
await page.keyboard.press("Escape");
if (await dialog.isVisible()) throw new Error("Escape did not close DatePicker dialog.");
const triggerFocused = await page.getByRole("button", { name: /기준 날짜/ }).evaluate((node) => node === document.activeElement);
if (!triggerFocused) throw new Error("DatePicker did not restore trigger focus.");
const narrow = await browser.newPage({ viewport: { width: 320, height: 800 } });
await narrow.goto(baseUrl, { waitUntil: "networkidle" });
const overflow = await narrow.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
if (overflow) throw new Error("Design Docs overflows at 320px.");
await page.addScriptTag({ content: axe.source });
const accessibility = await page.evaluate(async () => globalThis.axe.run());
if (accessibility.violations.length) throw new Error(`Axe violations: ${accessibility.violations.map(({ id, nodes }) => `${id} ${nodes.map(({ target }) => target.join(" ")).join(" | ")}`).join(", ")}`);
if (errors.length) throw new Error(`Browser errors: ${errors.join(" | ")}`);
await page.screenshot({ path: "/tmp/kimgseok-design-docs.png", fullPage: true });
await browser.close();
console.log("Design Docs browser verification passed: content, dialog keyboard/focus, 320px containment, axe, console.");
